"""
Stretch goal: auto-generated weekly eval report. Pulls a week of scored
interactions + alert history and renders a markdown summary -- score
trends, the worst-scoring queries (candidates for prompt/chunking fixes),
and any drift flags raised. Designed to be run on a schedule (cron,
GitHub Action, etc.) and posted somewhere (Slack, email, or just committed
to a `reports/` folder) rather than only viewed in the dashboard.
"""
import time
from datetime import datetime, timedelta

from app.core.db import recent_alerts, rolling_score_summary, worst_scoring_interactions

ONE_WEEK_SECONDS = 7 * 24 * 60 * 60


def generate_weekly_report(namespace: str) -> str:
    summary = rolling_score_summary(namespace, ONE_WEEK_SECONDS)
    worst = worst_scoring_interactions(namespace, ONE_WEEK_SECONDS, limit=10)
    alerts = [a for a in recent_alerts(namespace, limit=50)
              if a["timestamp"] >= time.time() - ONE_WEEK_SECONDS]

    period_end = datetime.utcnow()
    period_start = period_end - timedelta(days=7)

    lines = [
        f"# Weekly RAG Eval Report — {namespace}",
        f"**Period:** {period_start:%Y-%m-%d} to {period_end:%Y-%m-%d}",
        "",
        "## Score Summary",
        f"- Sampled interactions: **{summary.get('n', 0)}**",
        f"- Avg faithfulness: **{_fmt(summary.get('avg_faithfulness'))}**",
        f"- Avg relevance: **{_fmt(summary.get('avg_relevance'))}**",
        f"- Avg tone: **{_fmt(summary.get('avg_tone'))}**",
        f"- Thumbs up / down: **{summary.get('thumbs_up', 0)} / {summary.get('thumbs_down', 0)}**",
        "",
        "## Alerts This Week",
    ]

    if alerts:
        for a in alerts:
            ts = datetime.utcfromtimestamp(a["timestamp"]).strftime("%Y-%m-%d %H:%M UTC")
            lines.append(f"- `{ts}` **[{a['alert_type']}]** {a['message']}")
    else:
        lines.append("_No alerts fired this week._")

    lines += ["", "## Worst-Performing Queries (candidates for review)"]
    if worst:
        lines.append("| Query | Avg Score | Faithfulness | Relevance | Tone |")
        lines.append("|---|---|---|---|---|")
        for row in worst:
            q = row["query"].replace("|", "\\|")[:80]
            lines.append(
                f"| {q} | {row['avg_score']:.2f} | {row['faithfulness']:.2f} | "
                f"{row['relevance']:.2f} | {row['tone']:.2f} |"
            )
    else:
        lines.append("_No scored interactions this week._")

    lines += [
        "",
        "---",
        "_Auto-generated by the RAG Evaluation & Monitoring layer. "
        "Run `generate_weekly_report()` on a schedule to keep this current._",
    ]
    return "\n".join(lines)


def _fmt(value: float | None) -> str:
    return f"{value:.2f}" if value is not None else "n/a"
